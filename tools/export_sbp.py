"""Regenerate checked-in SBP wire references from the implemented contracts."""
import json
from pathlib import Path
from pydantic.json_schema import models_json_schema
from Ai.universal import contracts
from Ai.universal.host import Host
from Ai.universal.http import create_app
from Ai.universal.store import Store


def generate(directory: Path):
    directory.mkdir(parents=True, exist_ok=True)
    store = Store(":memory:")
    try:
        specification = create_app(Host(store, [])).openapi()
    finally:
        store.close()
    (directory / "openapi.json").write_text(json.dumps(specification, indent=2) + "\n")
    models = [value for value in vars(contracts).values() if isinstance(value, type)
              and issubclass(value, contracts.Wire) and value is not contracts.Wire]
    _, schemas = models_json_schema([(model, "validation") for model in models], title="SBP v0.1 wire contracts")
    schemas["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    (directory / "schemas.json").write_text(json.dumps(schemas, indent=2) + "\n")
    rows = ["# HTTP API reference", "", "Generated by `python -m tools.export_sbp`. Exact field types, required fields, limits, defaults and error responses are in [OpenAPI](openapi.json) and [JSON Schema](schemas.json).", "", "All routes require HTTPS. `B` is an administrator-provisioned bootstrap bearer; `S` is a session bearer. Agent-bound sessions are restricted to their agent. Additional role/scope restrictions are described in [SBP](specification.md).", "", "| Method | Path | Auth | Request body | Successful response (200) |", "| --- | --- | --- | --- | --- |"]
    def label(schema):
        if "$ref" in schema:
            return schema["$ref"].rsplit("/", 1)[-1]
        if schema.get("type") == "array":
            return "list[" + label(schema["items"]) + "]"
        return schema.get("type", "JSON")
    for path, methods in specification["paths"].items():
        for method, op in methods.items():
            auth = "B" if path == "/sbp/v0.1/sessions" else "S" if op.get("security") else "Public"
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            response = op["responses"]["200"]["content"]["application/json"]["schema"]
            rows.append(f"| {method.upper()} | `{path}` | {auth} | {label(body) if body else '—'} | {label(response)} |")
    rows += ["", "`GET /openapi.json` is also public. Event and audit reads accept `after` (integer ≥ 0, default 0) and `limit` (1–100, default 100). IDs match `[a-zA-Z0-9][a-zA-Z0-9_.:-]*` and are at most 96 characters. The schemas reject unknown object fields. Examples use placeholders for credentials; never commit real tokens.", ""]
    (directory / "api-reference.md").write_text("\n".join(rows))


if __name__ == "__main__":
    generate(Path(__file__).resolve().parents[1] / "docs" / "sbp")
